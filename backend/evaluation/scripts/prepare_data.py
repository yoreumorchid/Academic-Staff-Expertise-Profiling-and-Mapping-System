"""Split a single hand-curated annotation spreadsheet into the three
files that ``iaa_kappa.py`` and ``eval_nlp.py`` consume.

Solo-developer workflow (no external annotators available)
----------------------------------------------------------
Because the lone developer plays every role (data collector, annotator
A, annotator B, arbitrator), we collect everything in ONE wide CSV and
let this script fan it out into the canonical evaluation artefacts:

    my_raw_annotation.csv  (input, hand-edited in Excel)
        publication_id, title, abstract,
        author_tags, ai_tags, final_gold_tags

    -> annotator_author.csv     (publication_id,title,abstract,gold_tags)
    -> annotator_ai.csv         (publication_id,title,abstract,gold_tags)
    -> gold_tags.jsonl          (publication_id,title,abstract,gold_tags=[...])

The two annotator CSVs feed ``iaa_kappa.py`` so we can still report
Cohen's kappa between "what the paper's own authors wrote" and "what
an LLM playing the role of a domain reviewer wrote". The JSONL file
feeds ``eval_nlp.py`` for the precision / recall / F1 study.

Future evolution (kept here as a contract for later phases)
-----------------------------------------------------------
When real staff or stakeholders join the project, the upgrade path is:

1. Keep the same wide CSV layout but add more annotator columns
   (e.g. ``staff_review_tags``, ``hod_review_tags``).
2. Extend this script with extra ``--emit annotator_<role>.csv``
   options so each new reviewer gets their own kappa-ready file.
3. Re-run ``iaa_kappa.py`` pairwise to track agreement drift over time.
4. Treat the curated ``final_gold_tags`` column as a living document:
   stakeholders may overwrite individual cells; downstream JSONL is
   regenerated by simply re-running this script, so no other code
   needs to change.

Usage
-----
::

    python -m evaluation.scripts.prepare_data \
        --raw evaluation/datasets/my_raw_annotation.csv
"""
from __future__ import annotations

import argparse
import csv
import json
import re
from pathlib import Path
from typing import Iterable


REQUIRED_COLUMNS = (
    "publication_id",
    "title",
    "abstract",
    "author_tags",
    "ai_tags",
    "final_gold_tags",
)


def _split_tags(raw: str) -> list[str]:
    """Accept comma / semicolon / pipe separated tag strings."""
    if not raw:
        return []
    parts = re.split(r"[;,|]", raw)
    return [p.strip() for p in parts if p and p.strip()]


def _write_annotator_csv(
    out_path: Path,
    rows: Iterable[dict],
    *,
    source_column: str,
) -> int:
    """Write a Kappa-ready CSV with the standard four columns."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with out_path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["publication_id", "title", "abstract", "gold_tags"])
        for row in rows:
            tags = _split_tags(row.get(source_column, ""))
            if not tags:
                # Skip rows where this annotator left the cell empty so
                # Cohen's kappa is not skewed by phantom "no tags" matches.
                continue
            writer.writerow(
                [
                    row["publication_id"].strip(),
                    row.get("title", "").strip(),
                    row.get("abstract", "").strip(),
                    ", ".join(tags),
                ]
            )
            count += 1
    return count


def _write_gold_jsonl(out_path: Path, rows: Iterable[dict]) -> int:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with out_path.open("w", encoding="utf-8") as fh:
        for row in rows:
            tags = _split_tags(row.get("final_gold_tags", ""))
            if not tags:
                # No arbitrated gold yet — leave it out of the eval set.
                continue
            abstract = (row.get("abstract") or "").strip()
            if not abstract:
                # eval_nlp.py needs raw text input; rows with no abstract
                # would silently inflate precision (empty predictions).
                continue
            fh.write(
                json.dumps(
                    {
                        "publication_id": row["publication_id"].strip(),
                        "title": (row.get("title") or "").strip(),
                        "abstract": abstract,
                        "gold_tags": tags,
                    },
                    ensure_ascii=False,
                )
                + "\n"
            )
            count += 1
    return count


def _load_raw(raw_path: Path) -> list[dict]:
    with raw_path.open(encoding="utf-8-sig", newline="") as fh:
        reader = csv.DictReader(fh)
        missing = [c for c in REQUIRED_COLUMNS if c not in (reader.fieldnames or [])]
        if missing:
            raise SystemExit(
                "my_raw_annotation.csv is missing required columns: "
                + ", ".join(missing)
                + f"\nExpected columns: {', '.join(REQUIRED_COLUMNS)}"
            )
        rows = [dict(r) for r in reader if (r.get("publication_id") or "").strip()]
    if not rows:
        raise SystemExit("No usable rows found in " + str(raw_path))
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--raw",
        type=Path,
        default=Path("evaluation/datasets/my_raw_annotation.csv"),
        help="Path to the hand-curated wide CSV.",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("evaluation/datasets"),
        help="Directory where the three output files are written.",
    )
    args = parser.parse_args()

    rows = _load_raw(args.raw)

    author_path = args.out_dir / "annotator_author.csv"
    ai_path = args.out_dir / "annotator_ai.csv"
    gold_path = args.out_dir / "gold_tags.jsonl"

    n_author = _write_annotator_csv(author_path, rows, source_column="author_tags")
    n_ai = _write_annotator_csv(ai_path, rows, source_column="ai_tags")
    n_gold = _write_gold_jsonl(gold_path, rows)

    print("Done.")
    print(f"  Annotator A (author keywords)  -> {author_path}  [{n_author} rows]")
    print(f"  Annotator B (AI keywords)      -> {ai_path}  [{n_ai} rows]")
    print(f"  Arbitrated gold (for eval_nlp) -> {gold_path}  [{n_gold} rows]")
    print()
    print("Next steps:")
    print("  1) python -m evaluation.scripts.iaa_kappa --a "
          + str(author_path) + " --b " + str(ai_path))
    print("  2) python -m evaluation.scripts.eval_nlp --gold "
          + str(gold_path) + " --k 5")


if __name__ == "__main__":
    main()
